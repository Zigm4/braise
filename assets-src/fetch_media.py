#!/usr/bin/env python3
"""Fetch exercise photos from free-exercise-db and emit the media module.

Photos: yuhonas/free-exercise-db (Unlicense, public domain), two frames per
exercise (start and end position), committed into public/exercises/.
Videos: hand-verified links to MuscleWiki (French pages) and Greg Brookes'
kettlebellsworkouts.com for the ballistic lifts MuscleWiki lacks.

Run: python3 assets-src/fetch_media.py
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FEDB_JSON = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json"
FEDB_RAW = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/"
OUT_DIR = os.path.join(ROOT, "public", "exercises")
OUT_TS = os.path.join(ROOT, "src", "data", "exerciseMedia.ts")

MW = "https://musclewiki.com/fr-fr/exercise/"
KBW = "https://kettlebellsworkouts.com/"

# ourId -> (free-exercise-db exact name or None, video url or None)
MAPPING = {
    "kb_swing": (None, MW + "kettlebell-swing"),
    "kb_swing_1b": ("One-Arm Kettlebell Swings", KBW + "kettlebell-swing-one-hand/"),
    "kb_deadlift": (None, KBW + "kettlebell-deadlift/"),
    "kb_sdhp": ("Kettlebell Sumo High Pull", KBW + "teaching-points-for-the-kettlebell-high-pull/"),
    "kb_snatch": ("One-Arm Kettlebell Snatch", KBW + "teaching-points-for-the-kettlebell-snatch/"),
    "goblet_squat": ("Goblet Squat", MW + "kettlebell-goblet-squat"),
    "kb_squat": ("Front Squats With Two Kettlebells", KBW + "teaching-points-for-the-kettlebell-squat/"),
    "rev_lunge": ("Dumbbell Rear Lunge", MW + "kettlebell-single-arm-reverse-lunge"),
    "kb_row": ("One-Arm Kettlebell Row", KBW + "kettlebell-row-exercise/"),
    "kb_curl": ("Dumbbell Bicep Curl", MW + "kettlebell-goblet-curl"),
    "sa_press": ("Alternating Kettlebell Press", MW + "kettlebell-single-arm-press"),
    "floor_press": ("One-Arm Kettlebell Floor Press", MW + "kettlebell-chest-press-single"),
    "kb_chest_press": ("Alternating Floor Press", MW + "kettlebell-chest-press-single"),
    "half_tgu": ("Kettlebell Turkish Get-Up (Lunge style)", KBW + "7-steps-of-the-kettlebell-turkish-get-up/"),
    "tgu": ("Kettlebell Turkish Get-Up (Squat style)", KBW + "7-steps-of-the-kettlebell-turkish-get-up/"),
    "windmill": ("Kettlebell Windmill", MW + "kettlebell-windmill"),
    "kb_situp": ("Sit-Up", MW + "kettlebell-situp"),
    "farmer": ("Farmer's Walk", MW + "kettlebell-farmers-carry"),
    "suitcase": (None, KBW + "kettlebell-suitcase-carry/"),
    "waiter": (None, None),
    "kb_clean": ("One-Arm Kettlebell Clean", KBW + "teaching-points-for-the-kettlebell-clean/"),
    "kb_clean_press": ("One-Arm Kettlebell Clean and Jerk", KBW + "kettlebell-clean-and-press/"),
    "kb_push_press": ("One-Arm Kettlebell Push Press", KBW + "kettlebell-push-press/"),
    "kb_jerk": ("One-Arm Kettlebell Jerk", None),
    "kb_thruster": ("Kettlebell Thruster", KBW + "kettlebell-thruster/"),
    "goblet_lunge": ("Dumbbell Lunges", MW + "kettlebell-single-arm-forward-lunge"),
    "step_up": ("Dumbbell Step Ups", MW + "kettlebell-step-up"),
    "gorilla_row": ("Two-Arm Kettlebell Row", None),
    "renegade_row": ("Alternating Renegade Row", KBW + "kettlebell-renegade-row/"),
    "racked_carry": (None, None),
    "overhead_carry": (None, KBW + "kettlebell-overhead-carry/"),
    "kb_sumo_deadlift": (None, None),
    "kb_flye": ("Dumbbell Flyes", MW + "kettlebell-single-arm-chest-fly"),
    "kb_leg_raises": ("Flat Bench Lying Leg Raise", MW + "laying-leg-raises"),
    "kb_overhead_swing": (None, None),
}


def fetch(url: str, dest: str) -> None:
    subprocess.run(["curl", "-sSfL", "--max-time", "60", url, "-o", dest], check=True)


def main():
    tmp = os.path.join(ROOT, "assets-src", ".fedb.json")
    fetch(FEDB_JSON, tmp)
    with open(tmp) as f:
        db = json.load(f)
    os.remove(tmp)
    by_name = {e["name"]: e for e in db}

    media = {}
    for our_id, (fedb_name, video) in MAPPING.items():
        entry = {}
        if fedb_name:
            fedb = by_name.get(fedb_name)
            if fedb is None:
                raise SystemExit(f"{our_id}: '{fedb_name}' not found in free-exercise-db")
            paths = []
            os.makedirs(os.path.join(OUT_DIR, our_id), exist_ok=True)
            for i, img in enumerate(fedb["images"][:2]):
                dest = os.path.join(OUT_DIR, our_id, f"{i}.jpg")
                if not os.path.exists(dest):
                    fetch(FEDB_RAW + img.replace(" ", "%20"), dest)
                paths.append(f"exercises/{our_id}/{i}.jpg")
            entry["photos"] = paths
        if video:
            entry["videoUrl"] = video
        if entry:
            media[our_id] = entry

    ts = (
        "// Auto-generated by assets-src/fetch_media.py. Do not edit by hand.\n"
        "// Photos: free-exercise-db (Unlicense, public domain), committed in public/exercises/.\n"
        "// Videos: MuscleWiki (fr) and kettlebellsworkouts.com, hand-verified links.\n"
        "export interface ExerciseMedia {\n"
        "  photos?: string[]\n"
        "  videoUrl?: string\n"
        "}\n\n"
        "export const EXERCISE_MEDIA: Record<string, ExerciseMedia> = "
        + json.dumps(media, indent=2)
        + "\n"
    )
    with open(OUT_TS, "w") as f:
        f.write(ts)
    photo_count = sum(1 for m in media.values() if "photos" in m)
    video_count = sum(1 for m in media.values() if "videoUrl" in m)
    print(f"wrote {OUT_TS}: {photo_count} exercises with photos, {video_count} with video links")


if __name__ == "__main__":
    main()
